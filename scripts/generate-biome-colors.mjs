#!/usr/bin/env node
/**
 * Generate src/worldgen/biomeColors.data.ts: per-biome grass / foliage / water colours (vanilla BiomeSpecialEffects +
 * the grass/foliage colormaps), indexed like DECORATION_BIOME_LIST (sorted biome file names).
 *
 *   node scripts/generate-biome-colors.mjs
 */
import fs from 'node:fs';
import zlib from 'node:zlib';
import { execFileSync } from 'node:child_process';

const ROOT = 'data/minecraft/worldgen/biome';
const ZIP = 'public/packs/default-resource-pack.zip';

function readPng(path) {
  const buf = execFileSync('unzip', ['-p', ZIP, path], { maxBuffer: 1 << 26 });
  let off = 8, w = 0, h = 0, depth = 0, type = 0, interlace = 0;
  const idat = []; let plte = null;
  while (off < buf.length) {
    const len = buf.readUInt32BE(off), name = buf.toString('ascii', off + 4, off + 8), data = buf.subarray(off + 8, off + 8 + len);
    if (name === 'IHDR') { w = data.readUInt32BE(0); h = data.readUInt32BE(4); depth = data[8]; type = data[9]; interlace = data[12]; }
    else if (name === 'PLTE') plte = data;
    else if (name === 'IDAT') idat.push(data);
    off += 12 + len;
  }
  if (depth !== 8 || interlace !== 0) throw new Error('unsupported png ' + path);
  const bpp = { 0: 1, 2: 3, 3: 1, 4: 2, 6: 4 }[type];
  const raw = zlib.inflateSync(Buffer.concat(idat));
  const stride = w * bpp, px = Buffer.alloc(stride * h);
  for (let y = 0; y < h; y++) {
    const f = raw[y * (stride + 1)], row = y * stride, src = y * (stride + 1) + 1;
    for (let i = 0; i < stride; i++) {
      const a = i >= bpp ? px[row + i - bpp] : 0, b = y ? px[row - stride + i] : 0, c = i >= bpp && y ? px[row - stride + i - bpp] : 0;
      let v = raw[src + i];
      if (f === 1) v += a; else if (f === 2) v += b; else if (f === 3) v += (a + b) >> 1;
      else if (f === 4) { const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c); v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c; }
      px[row + i] = v & 255;
    }
  }
  const rgb = (x, y) => {
    const i = (y * w + x) * bpp;
    if (type === 3) return (plte[px[i] * 3] << 16) | (plte[px[i] * 3 + 1] << 8) | plte[px[i] * 3 + 2];
    if (type === 0 || type === 4) return (px[i] << 16) | (px[i] << 8) | px[i];
    return (px[i] << 16) | (px[i + 1] << 8) | px[i + 2];
  };
  return { w, h, rgb };
}

const grassMap = readPng('assets/minecraft/textures/colormap/grass.png');
const foliageMap = readPng('assets/minecraft/textures/colormap/foliage.png');
/** GrassColor.get / FoliageColor.get */
const lookup = (map, temperature, downfall) => {
  const t = Math.min(1, Math.max(0, temperature));
  const d = Math.min(1, Math.max(0, downfall)) * t;
  const x = Math.trunc((1 - t) * 255), y = Math.trunc((1 - d) * 255);
  return map.rgb(x, y);
};
const hex = (s) => parseInt(s.replace('#', ''), 16);

const names = fs.readdirSync(ROOT).filter((f) => f.endsWith('.json')).sort().map((f) => f.slice(0, -5));
const grass = [], foliage = [], water = [], modifier = [];
for (const n of names) {
  const b = JSON.parse(fs.readFileSync(`${ROOT}/${n}.json`, 'utf8'));
  const e = b.effects ?? {};
  grass.push(e.grass_color ? hex(e.grass_color) : lookup(grassMap, b.temperature, b.downfall));
  foliage.push(e.foliage_color ? hex(e.foliage_color) : lookup(foliageMap, b.temperature, b.downfall));
  water.push(e.water_color ? hex(e.water_color) : 0x3f76e4);
  modifier.push({ none: 0, dark_forest: 1, swamp: 2 }[e.grass_color_modifier ?? 'none']);
}
const body = `// Generated by scripts/generate-biome-colors.mjs. Do not hand-edit.
// Indexed like DECORATION_BIOME_LIST. Colours are 0xRRGGBB; modifier: 0 none, 1 dark_forest, 2 swamp.
export const BIOME_GRASS_COLOR: number[] = ${JSON.stringify(grass)};
export const BIOME_FOLIAGE_COLOR: number[] = ${JSON.stringify(foliage)};
export const BIOME_WATER_COLOR: number[] = ${JSON.stringify(water)};
export const BIOME_GRASS_MODIFIER: number[] = ${JSON.stringify(modifier)};
`;
fs.writeFileSync('src/worldgen/biomeColors.data.ts', body);
const i = names.indexOf('plains');
console.log(names.length, 'biomes; plains grass', grass[i].toString(16), 'foliage', foliage[i].toString(16));
